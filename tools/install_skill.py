"""Install a discoverable Codex entry point that routes to the tracked workbench skill."""

import argparse
import json
import os
from pathlib import Path
import tempfile


ROOT = Path(__file__).resolve().parent.parent
NAME = "ethernetip-workbench"
MARKER = "<!-- Generated by EthernetIPWorkbench tools/install_skill.py -->"


def install(destination):
    source = ROOT / ".agents" / "skills" / NAME / "SKILL.md"
    if not source.is_file():
        raise ValueError(f"Tracked skill is missing at {source}")
    destination = destination.expanduser().resolve()
    if destination == source.parent:
        raise ValueError("Select an entry-point directory distinct from the tracked skill")
    target = destination / "SKILL.md"
    if target.exists() and MARKER not in target.read_text(encoding="utf-8"):
        raise ValueError(f"Preserving an existing skill that this installer did not create at {target}")
    description = (
        "Configure, operate or extend EthernetIPWorkbench, the Windows EtherNet/IP scanner, "
        "using its maintained profiles, CLI, CSV capture and HTTP, MQTT or shared-memory documentation."
    )
    text = (
        f"---\nname: {NAME}\ndescription: {json.dumps(description)}\n---\n\n"
        f"{MARKER}\n\n# EthernetIPWorkbench\n\n"
        f"The configured workbench root is {ROOT.as_posix()}.\n\n"
        f"Read the canonical skill at [{source.name}](<{source.as_posix()}>) before this workflow. "
        "Resolve its relative references from that canonical file. "
        "Follow the current user's device and write authorization. "
        "If the root has moved, locate the checkout and rerun tools/install_skill.py there.\n"
    )
    if target.exists() and target.read_text(encoding="utf-8") == text:
        return target
    destination.mkdir(parents=True, exist_ok=True)
    pending = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", newline="\n", dir=destination,
            prefix=".workbench-skill-", suffix=".tmp", delete=False,
        ) as stream:
            pending = Path(stream.name)
            stream.write(text)
        os.replace(pending, target)
    finally:
        if pending is not None:
            pending.unlink(missing_ok=True)
    return target


def main():
    codex_root = Path(os.environ.get("CODEX_HOME") or Path.home() / ".codex")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--destination", type=Path, default=codex_root / "skills" / NAME)
    args = parser.parse_args()
    try:
        target = install(args.destination)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Installed {target}")


if __name__ == "__main__":
    main()
